CREATE SCHEMA IF NOT EXISTS dw;

CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    day_of_month INTEGER NOT NULL,
    month_number INTEGER NOT NULL,
    month_name VARCHAR(20) NOT NULL,
    quarter_number INTEGER NOT NULL,
    year_number INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_product (
    product_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(200) NOT NULL,
    category VARCHAR(100) NOT NULL,
    CONSTRAINT uq_dim_product UNIQUE (product_name, category)
);

CREATE TABLE IF NOT EXISTS dw.dim_customer (
    customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(100) NOT NULL UNIQUE,
    customer_name VARCHAR(200) NOT NULL,
    city VARCHAR(100) NOT NULL
);

-- Grain: one row per order line. order_id may appear more than once if a
-- future source contains multiple products in the same order.
CREATE TABLE IF NOT EXISTS dw.fact_sales (
    sales_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(100) NOT NULL,
    order_date DATE NOT NULL REFERENCES dw.dim_date(full_date),
    date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    product_key BIGINT NOT NULL REFERENCES dw.dim_product(product_key),
    customer_key BIGINT NOT NULL REFERENCES dw.dim_customer(customer_key),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    total_amount NUMERIC(14,2) NOT NULL CHECK (total_amount >= 0),
    source_order_line_id VARCHAR(200) NOT NULL UNIQUE
);

CREATE INDEX IF NOT EXISTS idx_fact_sales_date_key ON dw.fact_sales(date_key);
CREATE INDEX IF NOT EXISTS idx_fact_sales_product_key ON dw.fact_sales(product_key);
CREATE INDEX IF NOT EXISTS idx_fact_sales_customer_key ON dw.fact_sales(customer_key);
